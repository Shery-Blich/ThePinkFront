// Copies the active trivia questions from MongoDB into Game/data/fallback-questions.json,
// the set the game falls back to when the backend is unreachable. Runs before every game
// build (npm "prebuild"), so each deploy ships the questions as they are in the admin panel.
//
// Never fails the build: if Mongo can't be reached or returns nothing usable, the existing
// file is kept and a warning is printed. Pass --strict to exit with an error instead.
//
// MONGODB_URI comes from the environment, else from backend/.env. A read-only user is enough.
import { existsSync, readFileSync, writeFileSync } from 'fs';
import { createRequire } from 'module';
import { dirname, join } from 'path';
import { fileURLToPath } from 'url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const outFile = join(root, 'Game', 'data', 'fallback-questions.json');
const strict = process.argv.includes('--strict');
const inCI = !!process.env.GITHUB_ACTIONS;

function warn(message) {
  // Shows up as an annotation on the GitHub Actions run
  console.warn(inCI ? `::warning title=Fallback questions not synced::${message}` : `[sync-questions] ${message}`);
  if (strict) process.exit(1);
  console.warn('[sync-questions] Keeping the existing fallback questions.');
  process.exit(0);
}

function readMongoUri() {
  if (process.env.MONGODB_URI) return process.env.MONGODB_URI;
  const envFile = join(root, 'backend', '.env');
  if (!existsSync(envFile)) return null;
  const line = readFileSync(envFile, 'utf8')
    .split('\n')
    .find((l) => /^\s*MONGODB_URI\s*=/.test(l));
  return line ? line.slice(line.indexOf('=') + 1).trim().replace(/^["']|["']$/g, '') : null;
}

// Mongoose is a backend dependency; reuse it instead of adding a driver to the game
function loadMongoose() {
  try {
    return createRequire(join(root, 'backend', 'package.json'))('mongoose');
  } catch {
    return null;
  }
}

function isValid(q) {
  return (
    typeof q.text === 'string' && q.text.trim() &&
    Array.isArray(q.answers) && q.answers.length === 4 &&
    q.answers.every((a) => typeof a?.text === 'string' && a.text.trim()) &&
    Number.isInteger(q.correctAnswerIndex) && q.correctAnswerIndex >= 0 && q.correctAnswerIndex <= 3
  );
}

const uri = readMongoUri();
if (!uri) warn('MONGODB_URI is not set (env or backend/.env).');

const mongoose = loadMongoose();
if (!mongoose) warn('mongoose not found. Run `npm --prefix backend install` first.');

const conn = mongoose.createConnection(uri, { serverSelectionTimeoutMS: 10000 });
let questions;
try {
  await conn.asPromise();
  questions = await conn.db
    .collection('questions')
    .find({ isActive: true }, { projection: { text: 1, answers: 1, correctAnswerIndex: 1 } })
    // Same order as the game and admin panel (QUESTION_SORT in backend/src/models/Question.js)
    .sort({ order: 1, createdAt: 1 })
    .toArray();
} catch (err) {
  warn(`Could not read questions from MongoDB: ${err.message}`);
} finally {
  await conn.close().catch(() => {});
}

if (questions.length === 0) warn('MongoDB returned no active questions.');
const invalid = questions.filter((q) => !isValid(q));
if (invalid.length > 0) warn(`${invalid.length} question(s) are malformed: ${invalid.map((q) => q._id).join(', ')}`);

const next = questions.map((q) => ({
  text: q.text,
  answers: q.answers.map((a) => a.text),
  correctAnswerIndex: q.correctAnswerIndex,
}));

// Only rewrite when the questions changed, so builds don't dirty the file with a new timestamp
const current = existsSync(outFile) ? JSON.parse(readFileSync(outFile, 'utf8')) : null;
if (current && JSON.stringify(current.questions) === JSON.stringify(next)) {
  console.log(`[sync-questions] Fallback questions already up to date (${next.length}).`);
} else {
  const data = {
    _comment: 'Generated by scripts/sync-questions.mjs from MongoDB before each build. Edit questions in the admin panel, not here.',
    syncedAt: new Date().toISOString(),
    questions: next,
  };
  writeFileSync(outFile, `${JSON.stringify(data, null, 2)}\n`);
  console.log(`[sync-questions] Updated fallback questions (${next.length}).`);
}
